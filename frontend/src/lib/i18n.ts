const DICT: Record<Lang, Record<Key, string | string[]>> = { uk, en }

function pluralIndex(lang: Lang, n: number): number {
  if (lang === 'en') return n === 1 ? 0 : 1
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return 0
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1
  return 2
}

export type Translate = (key: Key, vars?: Record<string, string | number>) => string

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const entry = DICT[lang][key]
  let text = Array.isArray(entry) ? entry[pluralIndex(lang, Number(vars.n ?? 0))] : entry
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

export function useT(): { t: Translate; lang: Lang } {
  const lang = useSession((s) => s.lang)
  return { t: (key, vars) => translate(lang, key, vars), lang }
}

